import { test, expect } from '@playwright/test';

test('This was generated by codegen', async ({ page }) => {
  // navigate to URL
  await page.goto('https://the-internet.herokuapp.com/login');
  // click on username form field
  await page.getByRole('textbox', { name: 'Username' }).click();
  //input username
  await page.getByRole('textbox', { name: 'Username' }).fill('tomsmith');
  //click on password field
  await page.getByRole('textbox', { name: 'Password' }).click();
  //input password
  await page.getByRole('textbox', { name: 'Password' }).fill('SuperSecretPassword!');
  // find & click login button
  await page.getByRole('button', { name: /Login/i }).click();
  // ensure you're on secure login page by checking element is present
  await expect(page.getByText('You logged into a secure area')).toBeVisible();
  // double check you're on secure login page by checking other element is present
  await expect(page.locator('h4')).toContainText('Welcome to the Secure Area. When you are done click logout below.');
  // find & click logout button
  await page.getByRole('link', { name: 'Logout' }).click();
  
  //await page.pause();
});